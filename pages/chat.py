# ============================================================
# AI 채팅 페이지
# 파일 위치: pages/chat.py
#
# 기존 main.py는 수정하지 않습니다.
# 이 파일 하나만으로 AI 채팅 페이지가 작동합니다.
# ============================================================

import streamlit as st
from openai import OpenAI


# ------------------------------------------------------------
# 1. 페이지 기본 설정
# ------------------------------------------------------------

st.set_page_config(
    page_title="AI 정보 선생님",
    page_icon="🤖",
    layout="centered"
)


# ------------------------------------------------------------
# 2. 기본 성격 문장
#
# 사이드바에서 사용자가 직접 수정할 수 있습니다.
# ------------------------------------------------------------

DEFAULT_PERSONALITY = (
    "너는 중고등학생에게 설명하는 친절한 정보 선생님이야. "
    "어려운 말은 쉬운 말로 바꿔 주고, "
    "반드시 순수 한국어로만 답해."
)


# ------------------------------------------------------------
# 3. 세 가지 말투의 추가 설정
#
# 사용자가 사이드바에서 말투를 바꾸면
# 다음 답변부터 바로 해당 설정이 적용됩니다.
# ------------------------------------------------------------

TONE_INSTRUCTIONS = {
    "친절한 선생님": (
        "학생이 이해하기 쉽도록 차근차근 설명해. "
        "어려운 개념은 쉬운 예시를 들어 설명하고, "
        "학생의 질문을 존중하면서 따뜻하고 친절하게 답해."
    ),

    "시크한 전문가": (
        "불필요하게 길게 설명하지 말고 핵심을 정확하게 전달해. "
        "전문적인 내용을 다루되 학생이 이해할 수 있는 수준으로 "
        "깔끔하고 논리적으로 설명해."
    ),

    "되물어보는 조교": (
        "학생이 공부와 관련된 질문을 했을 때 정답을 바로 알려주지 마. "
        "먼저 문제를 해결하는 데 도움이 되는 힌트를 하나만 제시하고 "
        "학생에게 다음 단계가 무엇인지 되물어봐. "
        "학생이 자신의 답이나 풀이를 스스로 말하면 그때 맞는지 확인해 주고, "
        "틀렸다면 어디를 다시 생각해 보면 좋은지 알려줘. "
        "단순한 사실 질문처럼 스스로 답을 만들어 볼 필요가 없는 질문에는 "
        "필요한 정보를 직접 설명해도 된다."
    )
}


# ------------------------------------------------------------
# 4. 대화 기록 초기화
# ------------------------------------------------------------

if "messages" not in st.session_state:
    st.session_state.messages = []


# ------------------------------------------------------------
# 5. 사이드바
# ------------------------------------------------------------

with st.sidebar:

    st.header("⚙️ 채팅 설정")

    # --------------------------------------------------------
    # 말투 선택
    # --------------------------------------------------------

    st.subheader("말투 고르기")

    selected_tone = st.selectbox(
        "AI의 말투를 선택하세요.",
        [
            "친절한 선생님",
            "시크한 전문가",
            "되물어보는 조교"
        ],
        label_visibility="collapsed"
    )


    # --------------------------------------------------------
    # 성격 문장 직접 수정
    # --------------------------------------------------------

    st.subheader("AI 성격")

    personality = st.text_area(
        "AI의 성격을 직접 설정하세요.",
        value=DEFAULT_PERSONALITY,
        height=150,
        help="이 문장은 AI에게만 전달되며 채팅 화면에는 표시되지 않습니다."
    )


    # --------------------------------------------------------
    # 현재 선택된 말투에 대한 간단한 설명
    # --------------------------------------------------------

    st.caption(
        f"현재 말투: {selected_tone}"
    )


    # --------------------------------------------------------
    # 구분선
    # --------------------------------------------------------

    st.divider()


    # --------------------------------------------------------
    # 대화 지우기 버튼
    # --------------------------------------------------------

    if st.button(
        "🗑️ 대화 지우기",
        use_container_width=True
    ):

        # 지금까지 저장된 대화 내용을 모두 삭제합니다.
        st.session_state.messages = []

        # 화면도 바로 다시 불러옵니다.
        st.rerun()


# ------------------------------------------------------------
# 6. Gemini API 연결
#
# API 키는 코드에 직접 적지 않습니다.
# Streamlit Secrets의 GEMINI_API_KEY를 사용합니다.
# ------------------------------------------------------------

try:

    api_key = st.secrets["GEMINI_API_KEY"]

    client = OpenAI(
        api_key=api_key,
        base_url="https://generativelanguage.googleapis.com/v1beta/openai/"
    )

except Exception:

    st.error(
        "AI 연결 설정을 불러오지 못했습니다. 관리자에게 확인해 주세요."
    )

    st.stop()


# ------------------------------------------------------------
# 7. 화면 제목
# ------------------------------------------------------------

st.title("🤖 AI 정보 선생님")
st.caption("궁금한 것을 질문해 보세요.")


# ------------------------------------------------------------
# 8. 기존 대화 화면에 표시
# ------------------------------------------------------------

for message in st.session_state.messages:

    with st.chat_message(message["role"]):
        st.markdown(message["content"])


# ------------------------------------------------------------
# 9. 채팅 입력창
# ------------------------------------------------------------

user_input = st.chat_input(
    "메시지를 입력하세요."
)


# ------------------------------------------------------------
# 10. 사용자가 메시지를 보냈을 때
# ------------------------------------------------------------

if user_input:

    # --------------------------------------------------------
    # 사용자의 메시지를 대화 기록에 저장
    # --------------------------------------------------------

    st.session_state.messages.append(
        {
            "role": "user",
            "content": user_input
        }
    )


    # --------------------------------------------------------
    # 사용자의 말풍선 표시
    # --------------------------------------------------------

    with st.chat_message("user"):
        st.markdown(user_input)


    # --------------------------------------------------------
    # AI 답변 말풍선
    # --------------------------------------------------------

    with st.chat_message("assistant"):

        # AI 답변이 실시간으로 표시될 공간
        answer_box = st.empty()


        # ----------------------------------------------------
        # AI에게 전달할 성격 구성
        #
        # 기본 성격 + 현재 선택한 말투를 합칩니다.
        # 사이드바에서 설정을 바꾸면 다음 답변부터
        # 새로운 설정이 적용됩니다.
        # ----------------------------------------------------

        system_prompt = (
            personality.strip()
            + "\n\n"
            + "추가 말투 지침:\n"
            + TONE_INSTRUCTIONS[selected_tone]
        )


        system_message = {
            "role": "system",
            "content": system_prompt
        }


        # ----------------------------------------------------
        # 지금까지의 대화 + 현재 성격 설정을 함께 전달
        #
        # 이전 대화를 전부 보내므로 AI가 대화의 흐름을
        # 이어서 이해할 수 있습니다.
        # ----------------------------------------------------

        messages_to_send = [
            system_message
        ] + st.session_state.messages


        # ----------------------------------------------------
        # Gemini API 호출
        #
        # stream=True를 사용해서 답변이 한꺼번에 나타나는
        # 것이 아니라 글자가 실시간으로 흘러나오게 합니다.
        # ----------------------------------------------------

        try:

            stream = client.chat.completions.create(
                model="gemini-3.5-flash-lite",
                messages=messages_to_send,
                stream=True
            )


            # 지금까지 생성된 답변
            full_answer = ""


            # ------------------------------------------------
            # AI가 보내는 답변을 하나씩 받습니다.
            # ------------------------------------------------

            for chunk in stream:

                # 새로운 글자가 있는지 확인합니다.
                if (
                    chunk.choices
                    and chunk.choices[0].delta.content
                ):

                    new_text = chunk.choices[0].delta.content

                    # 새 글자를 기존 답변 뒤에 붙입니다.
                    full_answer += new_text

                    # 답변 끝에 커서를 표시해서
                    # 실시간으로 글자가 나오는 느낌을 줍니다.
                    answer_box.markdown(
                        full_answer + "▌"
                    )


            # ------------------------------------------------
            # 답변이 완성되면 커서를 제거합니다.
            # ------------------------------------------------

            answer_box.markdown(
                full_answer
            )


            # ------------------------------------------------
            # AI 답변을 대화 기록에 저장
            #
            # 다음 질문을 할 때 이전 AI 답변도 함께
            # Gemini에게 전달됩니다.
            # ------------------------------------------------

            st.session_state.messages.append(
                {
                    "role": "assistant",
                    "content": full_answer
                }
            )


        # ----------------------------------------------------
        # 오류 처리
        #
        # 복잡한 오류 내용을 사용자에게 그대로 보여주지
        # 않고 한국어 안내 문구만 표시합니다.
        # ----------------------------------------------------

        except Exception:

            answer_box.markdown(
                "잠시 문제가 생겼어요. 잠시 후 다시 시도해 주세요."
            )
